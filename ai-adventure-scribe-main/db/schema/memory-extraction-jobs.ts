/**
 * Memory extraction job queue (#846).
 *
 * The memory extraction API accepts a job and returns 202, then finishes it out
 * of band. The job used to live in the accepting process only, so every restart
 * (every deploy) discarded every accepted-but-unfinished job — along with the
 * quota it consumed. Accepted jobs are persisted here before the 202, so a
 * restart loses nothing: on startup the server resumes pending jobs, and
 * running jobs whose heartbeat went stale are reclaimed by updated_at.
 *
 * Quota is charged when a job completes, never when it is accepted, so a job
 * that never runs is never charged.
 */

import { boolean, index, integer, pgTable, text, timestamp, uuid } from 'drizzle-orm/pg-core';

import type { InferInsertModel, InferSelectModel } from 'drizzle-orm';

export const memoryExtractionJobs = pgTable(
  'memory_extraction_jobs',
  {
    // The id the 202 hands back. Generated by the route before the insert, not
    // by the DB, so the response id and the row id are always the same value.
    id: uuid('id').primaryKey(),
    // WorkOS user id. RLS is off, so every query on this table filters by owner.
    userId: text('user_id').notNull(),
    plan: text('plan').notNull(),
    sessionId: uuid('session_id').notNull(),
    campaignId: uuid('campaign_id'),
    characterId: text('character_id'),
    kind: text('kind').notNull(),
    // The full prompt, so a resumed job needs nothing but this row.
    prompt: text('prompt').notNull(),
    // sha256 of the canonical payload, for dedup visibility and diagnostics.
    payloadHash: text('payload_hash').notNull(),
    maxTokens: integer('max_tokens').notNull(),
    turn: integer('turn'),
    // pending | running | completed | failed. Transitions are guarded in the
    // store so two processes can never run or complete the same job twice.
    status: text('status').notNull().default('pending'),
    attempts: integer('attempts').notNull().default(0),
    // Quota is charged when the job completes, never before (#846).
    charged: boolean('charged').notNull().default(false),
    // The last failure, so a terminally failed job explains itself.
    error: text('error'),
    createdAt: timestamp('created_at', { withTimezone: true, mode: 'date' }).defaultNow().notNull(),
    updatedAt: timestamp('updated_at', { withTimezone: true, mode: 'date' }).defaultNow().notNull(),
    completedAt: timestamp('completed_at', { withTimezone: true, mode: 'date' }),
  },
  (table) => ({
    statusIdx: index('idx_memory_extraction_jobs_status').on(table.status),
    sessionIdx: index('idx_memory_extraction_jobs_session').on(table.sessionId),
  }),
);

export type MemoryExtractionJobRow = InferSelectModel<typeof memoryExtractionJobs>;
export type NewMemoryExtractionJobRow = InferInsertModel<typeof memoryExtractionJobs>;
