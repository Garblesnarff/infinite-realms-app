const fighterPayload = JSON.parse(
  readFileSync(
    resolve(
      dirname(fileURLToPath(import.meta.url)),
      '../../../../../shared/test-fixtures/background-gaming-cards.json',
    ),
    'utf8',
  ),
) as {
  equipment: Array<Record<string, unknown>>;
  stats: { dexterity: number };
};

describeWithDb('concrete background gaming choice (#893)', () => {
  let app: { handle: (request: Request) => Promise<Response> };
  let db: ReturnType<typeof realDb>;
  const createdIds: string[] = [];

  beforeAll(async () => {
    userId = testId('user-710');
    db = realDb();
    const pipeline = await importWithRealDb(async () => {
      const { createRequestPipelineApp } = await import('../../../http-pipeline.ts');
      const { charactersRoutes } = await import('../characters.ts');
      return { createRequestPipelineApp, charactersRoutes };
    });
    app = pipeline.createRequestPipelineApp().use(pipeline.charactersRoutes);
  });

  afterAll(async () => {
    for (const id of createdIds) {
      await db
        .delete(characters)
        .where(eq(characters.id, id))
        .catch(() => {});
    }
    await closeRealDb();
  });

  async function create(body: unknown): Promise<string> {
    const res = await app.handle(
      new Request('http://localhost/v1/characters', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(body),
      }),
    );
    const text = await res.text();
    expect(res.status, text.slice(0, 400)).toBe(201);
    const { id } = JSON.parse(text) as { id: string };
    createdIds.push(id);
    return id;
  }

  it('persists the pinned cards choice with both items, then retains it after item removal', async () => {
    const id = await create(fighterPayload);
    const [stored] = await db.select().from(characters).where(eq(characters.id, id));
    expect(stored.toolProficiencies).toBe("Thieves' tools,Gaming set (cards)");
    const items = await db
      .select()
      .from(characterEquipment)
      .where(eq(characterEquipment.characterId, id));
    expect(items.map((item) => item.itemName).sort()).toEqual(['Deck of cards', 'Dice set']);
    await db.delete(characterEquipment).where(eq(characterEquipment.characterId, id));
    const res = await app.handle(new Request(`http://localhost/v1/characters/${id}`));
    expect(res.status).toBe(200);
    const reloaded = await res.json();
    expect(reloaded.tool_proficiencies).toBe("Thieves' tools,Gaming set (cards)");
  });
});
